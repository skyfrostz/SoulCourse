  electives JSONB NOT NULL DEFAULT '[]'::jsonb,
  category TEXT NOT NULL CHECK (category IN ('experience', 'question', 'data')),
  grade TEXT NOT NULL,
  province TEXT NOT NULL,
  likes_count INTEGER NOT NULL DEFAULT 0 CHECK (likes_count >= 0),
  comments_count INTEGER NOT NULL DEFAULT 0 CHECK (comments_count >= 0),
  favorites_count INTEGER NOT NULL DEFAULT 0 CHECK (favorites_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ,
  search_vector TSVECTOR NOT NULL DEFAULT ''::tsvector
);

-- +goose StatementBegin
CREATE FUNCTION update_posts_search_vector() RETURNS trigger AS $$
BEGIN
  NEW.search_vector :=
    setweight(to_tsvector('simple', coalesce(NEW.title, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(NEW.content, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(NEW.author_name, '') || ' ' || coalesce(NEW.province, '') || ' ' || coalesce(NEW.grade, '') || ' ' || coalesce(NEW.tags::text, '') || ' ' || coalesce(NEW.electives::text, '')), 'C');
  RETURN NEW;
END
$$ LANGUAGE plpgsql;
-- +goose StatementEnd

CREATE TRIGGER trg_posts_search_vector
BEFORE INSERT OR UPDATE OF title, content, author_name, province, grade, tags, electives
ON posts
FOR EACH ROW
EXECUTE FUNCTION update_posts_search_vector();

